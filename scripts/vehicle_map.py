# make: kia | hyundai
def V(make, model_fa, model_en, gen, y1, y2=None, gen_fa=None):
    return {
        "make": make,
        "modelFa": model_fa,
        "modelEn": model_en,
        "gen": gen,
        "genFa": gen_fa or gen,
        "yearStart": y1,
        "yearEnd": y2,
    }


def display(v):
    if not v:
        return ""
    make_fa = "هیوندای" if v["make"] == "hyundai" else "کیا"
    return f'{make_fa} {v["modelFa"]} {v["gen"]}'.strip()


def years(v):
    if not v:
        return ""
    return f'{v["yearStart"]}–{v["yearEnd"]}' if v.get("yearEnd") else f'{v["yearStart"]} به بعد'


